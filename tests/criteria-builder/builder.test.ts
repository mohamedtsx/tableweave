import { expect, it } from "vitest";
import { parseDate } from "@internationalized/date";
import { builderActions, builderEditor, builderState, editorActions, readBuilderEditor, requireBuilderEditor } from "../../packages/heroui/src/filters/criteria-builder-host.js";
import { criteriaDateChild, criteriaDateState, readCriteriaDateState, readCriteriaDateToolbar, requireCriteriaDateState } from "../../packages/heroui/src/date/criteria-date-state.js";
import { fixture, required, numberRule, dateRule } from "./fixtures.js";

it("actual accepted baseline survives draft field/operator changes into Date; only Apply proposes", () => {
  const f = fixture(), unmount = f.store.mount(), actor = f.commit(), before = f.app.C.getSnapshot();
  const original = JSON.stringify(before.query.builder.rules.find(rule => rule.id === "n1"));
  editorActions.field(f.open("n1", "field"), "created");
  editorActions.operator(builderEditor(f.store, actor), "date.between");
  const e = readBuilderEditor(builderEditor(f.store, actor)), date = readCriteriaDateToolbar(e.frame.local.date, e.actor);
  expect(e.draft?.baseline).toBe(original);
  expect(e.draft?.id).toBe("n1");
  expect(date.draft.status).toBe("empty");
  const handle = required(date.handle);
  criteriaDateState.calendar(criteriaDateChild(handle, "point", "range"), { start: parseDate("2030-01-10"), end: parseDate("2030-01-11") });
  expect(f.app.C.getSnapshot()).toBe(before);
  editorActions.apply(builderEditor(f.store, actor));
  expect(f.observed.at(-1)?.status).toBe("proposed");
  expect(f.app.C.getSnapshot()).toBe(before);
  f.accept();
  expect(f.app.C.getSnapshot().query.builder.rules.find(rule => rule.id === "n1")).toMatchObject({ field: "created", operator: "date.between" });
  unmount();
});
it("existing Date operator changes keep the real original JSON and partial edits never become malformed seeds", () => {
  const f = fixture(), stop = f.store.mount(), actor = f.commit();
  const baseline = JSON.stringify(f.app.C.getSnapshot().query.builder.rules.find(rule => rule.id === "d1"));
  editorActions.operator(f.open("d1", "operator"), "date.between");
  const e = readBuilderEditor(builderEditor(f.store, actor)), toolbar = readCriteriaDateToolbar(e.frame.local.date, e.actor);
  expect(e.draft?.baseline).toBe(baseline);
  expect(toolbar.draft.status).toBe("empty");
  const nested = criteriaDateChild(required(toolbar.handle), "point", "range");
  criteriaDateState.editing(nested, "start");
  editorActions.apply(builderEditor(f.store, actor));
  expect(f.observed).toHaveLength(0);
  expect(f.app.C.getSnapshot().query.builder.rules).toContainEqual(dateRule);
  stop();
});
it("B commit preserves same-domain draft/text but captured A handlers cannot run; paging is not a reset", () => {
  const f = fixture(), stop = f.store.mount(), a = f.commit(), saved = f.open("n1");
  editorActions.number(saved, 0, "8e");
  const local = required(f.store.read()).local;
  f.external({ type: "sorting.change", update: [{ id: "id", desc: true }] });
  const b = f.commit();
  expect(a).not.toBe(b);
  expect(local.numbers.read(b)).toEqual(["8e"]);
  expect(() => editorActions.number(saved, 0, "999")).toThrow();
  expect(() => requireBuilderEditor(saved)).toThrow();
  expect(local.numbers.read(b)).toEqual(["8e"]);
  editorActions.number(builderEditor(f.store, b), 0, "8");
  editorActions.apply(builderEditor(f.store, b));
  f.accept();
  expect(f.app.C.getSnapshot().query.builder.rules.find(rule => rule.id === "n1")?.value).toBe(8);
  stop();
});
it("same-id changed accepted JSON fences final dispatch; Cancel and Builder Clear stay distinct from selection", () => {
  const f = fixture(), stop = f.store.mount(), actor = f.commit(), handle = f.open("n1"), accepted = f.app.C.getSnapshot();
  editorActions.number(handle, 0, "12");
  editorActions.cancel(handle);
  expect(f.app.C.getSnapshot()).toBe(accepted);
  const stale = f.open("n1");
  f.external({ type: "builder.commit", rule: { ...numberRule, value: 9 } });
  expect(() => editorActions.apply(stale)).toThrow();
  expect(f.observed).toHaveLength(0);
  f.commit();
  const frame = required(f.store.read());
  builderActions.clear(f.store, frame.actor, required(frame.local.receipt.read(frame.actor)).token);
  expect(f.app.C.getSnapshot().query.builder.rules).not.toHaveLength(0);
  f.accept();
  expect(f.app.C.getSnapshot().query.builder.rules).toHaveLength(0);
  expect(f.app.C.getSnapshot().selection).toEqual({ one: true });
  expect(() => f.store.require(actor)).toThrow();
  stop();
});
it("actual P begin denies old callbacks before retirement; slots are empty on a later genuine actor without replay", () => {
  const f = fixture(), stop = f.store.mount(), a = f.commit(), handle = f.open("d1");
  const frame = required(f.store.read()), nested = required(readCriteriaDateToolbar(frame.local.date, a).handle);
  criteriaDateState.text(criteriaDateChild(nested, "point", "instant"), "synthetic-private-invalid");
  frame.local.search.write(a, "synthetic-field-term");
  frame.local.error.write(a, "synthetic-notice");
  frame.local.announcement.write(a, "synthetic-announcement");
  frame.local.term.write(a, "synthetic-option-term");
  let deniedBeforeRetire = false;
  f.app.faults.beforeRetire = () => { deniedBeforeRetire = true; expect(() => requireBuilderEditor(handle)).toThrow(); expect(() => requireCriteriaDateState(nested)).toThrow(); f.reject(); };
  const target = f.reset();
  expect(deniedBeforeRetire).toBe(true);
  f.store.commit(f.props({ criteria: target }));
  const b = required(f.store.read()).actor;
  for (const [name, slot] of Object.entries(frame.local)) if (name !== "date" && name !== "receipt") expect((slot as typeof frame.local.error).read(b), name).toBeNull();
  expect(readCriteriaDateToolbar(frame.local.date, b).draft.status).toBe("empty");
  expect(f.app.C.getSnapshot().query.builder.rules).toContainEqual(dateRule);
  expect(f.app.C.getSnapshot().selection).toEqual({});
  stop();
});
it("Date text and handle family renew on B without reseeding; A cannot reach B", () => {
  const f = fixture(), stop = f.store.mount(), a = f.commit();
  f.open("d1");
  const bundle = required(f.store.read()).local.date, old = required(readCriteriaDateToolbar(bundle, a).handle), child = criteriaDateChild(old, "point", "instant");
  criteriaDateState.text(child, "partial milliseconds");
  const b = f.commit(), fresh = required(readCriteriaDateToolbar(bundle, b).handle);
  expect(() => readCriteriaDateState(child)).toThrow();
  expect(readCriteriaDateState(criteriaDateChild(fresh, "point", "instant")).text).toBe("partial milliseconds");
  expect(builderState(f.store, b).draft?.value).toBeNull();
  stop();
});
